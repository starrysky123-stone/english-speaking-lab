import assert from 'node:assert/strict';
import {materialDraft,validateMaterial,parseMaterialBackup,readMaterials,candidateSentences,isOriginalExcerpt} from '../app/materials.ts';
import {readState} from '../app/lab-utils.ts';
import {practiceContext} from '../lib/practice-context.ts';
const source='Our study investigates how attention influences memory. We recruited forty participants for a reading experiment. Participants read short passages and completed a recall task. The results suggest that focused attention supports accurate recall.';
const draft=materialDraft(source,'My study','academic','study.pdf');
assert.equal(draft.material.text,source);
assert.equal(draft.sentences.length,4);
assert.ok(draft.words.every(w=>source.toLowerCase().includes(w.word.toLowerCase())));
assert.ok(draft.words.every(w=>w.ipa===''&&w.meaning===''));
assert.ok(draft.sentences.every(s=>source.includes(s.en)&&s.zh===''));
assert.equal(isOriginalExcerpt(source,'Participants read short passages and completed a recall task.'),true);
assert.equal(isOriginalExcerpt(source,'We recruited one hundred participants.'),false);
assert.equal(validateMaterial(draft).id,draft.id);
const oneQuestion={...draft,questions:['What did you learn?'],hints:['I learned that…']};
assert.equal(validateMaterial(oneQuestion).questions.length,1);
assert.throws(()=>validateMaterial({...draft,questions:[]}));
assert.throws(()=>validateMaterial({...draft,words:[{word:'',meaning:'',ipa:'',tip:''}]}));
assert.throws(()=>materialDraft('中文教材沒有英文句子','x','daily','x'));
assert.throws(()=>materialDraft('English language '.repeat(5000),'x','daily','x'));
assert.equal(parseMaterialBackup(JSON.stringify({format:'speaking-lab-materials-v1',materials:[draft]}))[0].material.text,source);
assert.throws(()=>parseMaterialBackup('{"materials":[]}'));
assert.throws(()=>parseMaterialBackup('{not JSON'));
assert.equal(readMaterials([draft,{id:'bad'}]).length,1);
const stored={review:[{word:'hello'}],logs:[{id:'old-log'}],progress:{methods:2},goal:15};
globalThis.localStorage={getItem:()=>JSON.stringify(stored)};
const state=readState();assert.equal(state.logs[0].id,'old-log');assert.equal(state.progress.methods,2);assert.deepEqual(state.customLessons,[]);
assert.ok(practiceContext(draft.id,{title:draft.title,category:draft.category,role:draft.role,words:draft.words.map(w=>w.word),sentences:draft.sentences.map(s=>s.en)}));
assert.equal(practiceContext('custom-x',{title:'x',category:'academic',role:'role',words:['word'],sentences:['x'.repeat(700)]}),null);
assert.ok(practiceContext('methods',null));
console.log('Passed: source retention, no invented translations/IPA, variable exercise counts, backup validation, old-data migration, and custom AI-context validation.');
